func TestCatalog(t *testing.T) {
	in := input(t)
	specs := []ProfileSpec{{Name: "core", Description: "Core parts", Parts: []string{"7-2", "7-3", "7-4"}}}
	files, err := Catalog(in, "embedded", specs)
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{CatalogGoFileName, CatalogJSONFileName, CatalogGzipFileName, "LOCAL-ONLY.md"} {
		if _, ok := files[name]; !ok {
			t.Errorf("missing %s (%d files)", name, len(files))
		}
	}
	src := string(files[CatalogGoFileName])
	for _, want := range []string{
		"// Code generated by nsdctl generate catalog; DO NOT EDIT.", "package embedded", "//go:embed catalog_gen.json.gz\n",
		`Name:        "core"`, `{Standard: "IEC 61850-7-4", Version: "2007", Revision: "B", Release: 1}`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("catalog_gen.go lacks %q:\n%s", want, src)
		}
	}
	var doc struct {
		Format     int                `json:"format"`
		Namespaces []*model.Namespace `json:"namespaces"`
	}
	if err := json.Unmarshal(files[CatalogJSONFileName], &doc); err != nil {
		t.Fatal(err)
	}
	if doc.Format != FormatVersion || len(doc.Namespaces) != len(in.Profile.Namespaces()) {
		t.Errorf("catalog_gen.json: format %d, %d namespaces", doc.Format, len(doc.Namespaces))
	}
	// The embedded file is the same document, compact and compressed with
	// gzip, without name or time in its header: generating twice gives the
	// same bytes.
	zr, err := gzip.NewReader(bytes.NewReader(files[CatalogGzipFileName]))
	if err != nil {
		t.Fatal(err)
	}
	if zr.Name != "" || !zr.ModTime.IsZero() {
		t.Errorf("gzip header carries %q, %v", zr.Name, zr.ModTime)
	}
	compact, err := io.ReadAll(zr)
	if err != nil {
		t.Fatal(err)
	}
	var indented bytes.Buffer
	if err := json.Indent(&indented, compact, "", "  "); err != nil || indented.String()+"\n" != string(files[CatalogJSONFileName]) {
		t.Errorf("catalog_gen.json.gz differs from catalog_gen.json (%v)", err)
	}
	if again, err := Catalog(in, "embedded", specs); err != nil || !bytes.Equal(again[CatalogGzipFileName], files[CatalogGzipFileName]) {
		t.Errorf("gzip output is not deterministic: %v", err)
	}
	// The embedded namespaces load into a catalog again.
	srcs := make([]catalog.Source, len(doc.Namespaces))
	for i, ns := range doc.Namespaces {
		srcs[i] = ns
	}
	if _, err := catalog.New(srcs...); err != nil {
		t.Errorf("reloading the embedded namespaces: %v", err)
	}

	published := in
	published.Publish = true
	if files, err := Catalog(published, "embedded", nil); err != nil || files["LOCAL-ONLY.md"] != nil {
		t.Errorf("published catalog: %d files, %v", len(files), err)
	}
}

// Embed puts every release of a catalog into catalog_gen.json; the
// profiles still resolve to one release per part.
func TestCatalogEmbedsAllReleases(t *testing.T) {
	in := input(t)
	in.Embed = fixtures.Catalog(t)
	files, err := Catalog(in, "embedded", []ProfileSpec{
		{Name: "latest", Parts: []string{"7-4"}},
		{Name: "first", Parts: []string{"7-4@2007B1"}},
	})
	if err != nil {
		t.Fatal(err)
	}
	var doc struct {
		Namespaces []*model.Namespace `json:"namespaces"`
	}
	if err := json.Unmarshal(files[CatalogJSONFileName], &doc); err != nil {
		t.Fatal(err)
	}
	if len(doc.Namespaces) != len(in.Embed.Namespaces()) || len(doc.Namespaces) <= len(in.Profile.Namespaces()) {
		t.Errorf("%d embedded namespaces, want every release (%d)", len(doc.Namespaces), len(in.Embed.Namespaces()))
	}
	src := string(files[CatalogGoFileName])
	for _, want := range []string{"IEC 61850-7-4:2007B2", `Release: 2}`, `Name:        "first"`, `Release: 1}`} {
		if !strings.Contains(src, want) {
			t.Errorf("catalog_gen.go lacks %q", want)
		}
	}
	if err := (Policy{}).CheckPublish(in.Embed); !errors.Is(err, ErrPolicyRefused) {
		t.Errorf("CheckPublish(catalog) = %v", err)
	}
}

func TestCatalogErrors(t *testing.T) {
	in := input(t)
	if _, err := Catalog(Input{}, "embedded", nil); !errors.Is(err, model.ErrUnknownNamespace) {
		t.Errorf("no profile: %v", err)
	}
	if _, err := Catalog(in, "not a package", nil); err == nil {
		t.Error("invalid package name accepted")
	}
	if _, err := Catalog(in, "embedded", []ProfileSpec{{Name: "x", Parts: []string{"90-9"}}}); !errors.Is(err, model.ErrMissingDependency) {
		t.Errorf("missing part: %v", err)
	}
}

func TestNamespaceToken(t *testing.T) {
	for std, want := range map[string]string{
		"IEC 61850-7-420": "7_420", "(Tr)IEC61850-90-9": "90_9", "OTF TEST-EXT": "OTFTEST_EXT",
	} {
		if got := namespaceToken(model.NamespaceID{Standard: std}); got != want {
			t.Errorf("namespaceToken(%q) = %q, want %q", std, got, want)
		}
	}
}
