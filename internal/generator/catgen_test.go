func TestCatalog(t *testing.T) {
	in := input(t)
	specs := []ProfileSpec{{Name: "core", Description: "Core parts", Parts: []string{"7-2", "7-3", "7-4"}}}
	files, err := Catalog(in, "embedded", specs)
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{CatalogGoFileName, CatalogJSONFileName, "LOCAL-ONLY.md"} {
		if _, ok := files[name]; !ok {
			t.Errorf("missing %s (%d files)", name, len(files))
		}
	}
	src := string(files[CatalogGoFileName])
	for _, want := range []string{
		"// Code generated by nsdctl generate catalog; DO NOT EDIT.", "package embedded", "//go:embed catalog_gen.json",
		`Name:        "core"`, `{Standard: "IEC 61850-7-4", Version: "2007", Revision: "B", Release: 1}`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("catalog_gen.go lacks %q:\n%s", want, src)
		}
	}
	var doc struct {
		Format     int                `json:"format"`
		Namespaces []*model.Namespace `json:"namespaces"`
	}
	if err := json.Unmarshal(files[CatalogJSONFileName], &doc); err != nil {
		t.Fatal(err)
	}
	if doc.Format != FormatVersion || len(doc.Namespaces) != len(in.Profile.Namespaces()) {
		t.Errorf("catalog_gen.json: format %d, %d namespaces", doc.Format, len(doc.Namespaces))
	}
	// The embedded namespaces load into a catalog again.
	srcs := make([]catalog.Source, len(doc.Namespaces))
	for i, ns := range doc.Namespaces {
		srcs[i] = ns
	}
	if _, err := catalog.New(srcs...); err != nil {
		t.Errorf("reloading the embedded namespaces: %v", err)
	}

	published := in
	published.Publish = true
	if files, err := Catalog(published, "embedded", nil); err != nil || files["LOCAL-ONLY.md"] != nil {
		t.Errorf("published catalog: %d files, %v", len(files), err)
	}
}

func TestCatalogErrors(t *testing.T) {
	in := input(t)
	if _, err := Catalog(Input{}, "embedded", nil); !errors.Is(err, model.ErrUnknownNamespace) {
		t.Errorf("no profile: %v", err)
	}
	if _, err := Catalog(in, "not a package", nil); err == nil {
		t.Error("invalid package name accepted")
	}
	if _, err := Catalog(in, "embedded", []ProfileSpec{{Name: "x", Parts: []string{"90-9"}}}); !errors.Is(err, model.ErrMissingDependency) {
		t.Errorf("missing part: %v", err)
	}
}

func TestNamespaceToken(t *testing.T) {
	for std, want := range map[string]string{
		"IEC 61850-7-420": "7_420", "(Tr)IEC61850-90-9": "90_9", "OTF TEST-EXT": "OTFTEST_EXT",
	} {
		if got := namespaceToken(model.NamespaceID{Standard: std}); got != want {
			t.Errorf("namespaceToken(%q) = %q, want %q", std, got, want)
		}
	}
}
