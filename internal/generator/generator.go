// Package generator produces deterministic output from a namespace
// profile: Go declarations, Markdown documentation and JSON exports.
//
// Output derived from official NSD files is IEC-derived content. By
// default it is marked local-only and carries a LOCAL-ONLY.md notice;
// publishing is refused by [Policy] unless the lock file records a
// licensing decision that permits it for every source namespace.
package generator

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/otfabric/go-iec61850-model/catalog"
	"github.com/otfabric/go-iec61850-model/internal/sources"
	"github.com/otfabric/go-iec61850-model/model"
)

// FormatVersion is the version of the generated output format. It
// changes whenever the generator would write different bytes for the
// same input.
const FormatVersion = 4

// Marker identifies files written by the generator. Write and Check
// only replace or remove files that contain it near the top.
const Marker = "Code generated by nsdctl"

// Errors of the generator.
var (
	// ErrPolicyRefused: publishing output is not permitted for at least
	// one source namespace.
	ErrPolicyRefused = errors.New("generator: publishing refused by license policy")
	// ErrWouldOverwrite: the output directory contains files the
	// generator did not write.
	ErrWouldOverwrite = errors.New("generator: refusing to overwrite files not written by nsdctl")
)

// Input is what every generator works from.
type Input struct {
	// Profile is the namespace selection to generate from.
	Profile *catalog.Profile
	// ToolVersion is written into headers, e.g. "v0.3.0".
	ToolVersion string
	// IncludeDocText includes NSDoc titles and descriptions. They are
	// IEC text: keep such output local.
	IncludeDocText bool
	// Publish marks output as intended for distribution: no local-only
	// notice. Check the [Policy] before setting it.
	Publish bool
}

// Files maps slash-separated relative paths to contents.
type Files map[string][]byte

// Paths returns the paths in sorted order.
func (f Files) Paths() []string {
	out := make([]string, 0, len(f))
	for p := range f {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

// sourceLines describes the source namespaces, one per line, without
// local paths: ID and digests only, so output does not depend on where
// the packages are stored.
func (in Input) sourceLines() []string {
	var out []string
	for _, ns := range in.Profile.Namespaces() {
		line := ns.ID.String()
		if ns.Provenance.SHA256 != "" {
			line += " sha256:" + ns.Provenance.SHA256
		}
		if ns.Provenance.PackageSHA256 != "" {
			line += " package-sha256:" + ns.Provenance.PackageSHA256
		}
		out = append(out, line)
	}
	return out
}

func (in Input) distribution() string {
	if in.Publish {
		return "publishable (permitted by the lock file)"
	}
	return "local-only; derived from IEC NSD files, do not commit or publish (see docs/licensing.md of github.com/otfabric/go-iec61850-model)"
}

// headerLines is the provenance header shared by all outputs.
func (in Input) headerLines(kind string) []string {
	lines := []string{
		Marker + " generate " + kind + "; DO NOT EDIT.",
		"",
		fmt.Sprintf("Generator: nsdctl %s (output format %d)", orDev(in.ToolVersion), FormatVersion),
		"Distribution: " + in.distribution(),
		"Namespaces:",
	}
	for _, l := range in.sourceLines() {
		lines = append(lines, "  "+l)
	}
	if in.noticeFile(kind) != nil {
		lines = append(lines, "Attribution: derived from IEC code components, © IEC; see NOTICE.md for the notices and license.")
	}
	return lines
}

func orDev(v string) string {
	if v == "" {
		return "dev"
	}
	return v
}

// noticeFile lists, per source namespace, the attribution and the
// copyright notice and license its NSD document declares. The IEC Code
// Components license requires redistributed code components to retain
// the notice and to be attributed to IEC and the source standard. It
// returns nil when no namespace declares a copyright.
func (in Input) noticeFile(kind string) []byte {
	var b bytes.Buffer
	found := false
	for _, ns := range in.Profile.Namespaces() {
		if ns.Copyright.IsZero() {
			continue
		}
		if !found {
			b.WriteString("<!-- " + Marker + " generate " + kind + "; DO NOT EDIT. -->\n\n")
			b.WriteString("# Notices\n\n")
			b.WriteString("This output is derived from IEC code components. Each is attributed to IEC and\n")
			b.WriteString("the standard it is taken from, with the copyright notice and license it declares.\n")
			found = true
		}
		fmt.Fprintf(&b, "\n## %s\n\nSource: IEC code component %s, © IEC.\n", ns.ID, ns.ID)
		if c := ns.Copyright; c.LicenseURI != "" {
			fmt.Fprintf(&b, "License: %s (%s).\n", c.LicenseURI, orDash(c.LicenseKind))
		}
		if ns.Copyright.Notice != "" {
			b.WriteString("\n> " + ns.Copyright.Notice + "\n")
		}
	}
	if !found {
		return nil
	}
	return b.Bytes()
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

// addNotice adds NOTICE.md to files when the sources declare notices.
func (in Input) addNotice(files Files, kind string) {
	if n := in.noticeFile(kind); n != nil {
		files["NOTICE.md"] = n
	}
}

// localNotice is added to local-only output.
func (in Input) localNotice(kind string) []byte {
	var b bytes.Buffer
	b.WriteString("<!-- " + Marker + " generate " + kind + "; DO NOT EDIT. -->\n\n")
	b.WriteString("# Local-only output\n\n")
	b.WriteString("The files in this directory are derived from official IEC NSD files.\n")
	b.WriteString("Do not commit them, attach them to issues or releases, or publish them in\n")
	b.WriteString("CI caches or artifacts until a documented licensing decision permits it.\n")
	b.WriteString("See docs/licensing.md of github.com/otfabric/go-iec61850-model.\n\n")
	b.WriteString("Source namespaces:\n\n")
	for _, l := range in.sourceLines() {
		b.WriteString("- " + l + "\n")
	}
	return b.Bytes()
}

func (in Input) validate() error {
	if in.Profile == nil {
		return fmt.Errorf("%w: generator needs a profile", model.ErrUnknownNamespace)
	}
	return nil
}

// Policy decides whether output may be published.
type Policy struct {
	// Lock is the version lock; nil permits nothing.
	Lock *sources.Lock
}

// PolicyError lists the namespaces that block publishing.
type PolicyError struct {
	Blocked []string
}

func (e *PolicyError) Error() string {
	return fmt.Sprintf("generator: publishing refused by license policy: %s", strings.Join(e.Blocked, "; "))
}

func (e *PolicyError) Unwrap() error { return ErrPolicyRefused }

// CheckPublish permits publishing only when every namespace of the
// profile has a lock entry with redistribution "permitted" and, when
// the entry records a digest, the loaded document or package has that
// digest.
func (p Policy) CheckPublish(profile *catalog.Profile) error {
	var blocked []string
	for _, ns := range profile.Namespaces() {
		if p.Lock == nil {
			blocked = append(blocked, ns.ID.String()+": no lock file")
			continue
		}
		e, ok := p.Lock.Entry(ns.ID)
		switch {
		case !ok:
			blocked = append(blocked, ns.ID.String()+": not in the lock file")
		case !e.Permitted():
			blocked = append(blocked, ns.ID.String()+": redistribution is not permitted")
		case e.SHA256 != "" && e.SHA256 != ns.Provenance.SHA256 && e.SHA256 != ns.Provenance.PackageSHA256:
			blocked = append(blocked, ns.ID.String()+": loaded file does not match the locked sha256")
		}
	}
	if len(blocked) > 0 {
		return &PolicyError{Blocked: blocked}
	}
	return nil
}

// DiffKind classifies a difference found by [Check].
type DiffKind string

// Difference kinds.
const (
	DiffMissing DiffKind = "missing"
	DiffChanged DiffKind = "changed"
	DiffStale   DiffKind = "stale"
)

// Difference is a file whose content on disk differs from the
// generated content.
type Difference struct {
	Path string   `json:"path"`
	Kind DiffKind `json:"kind"`
}

// isGenerated reports whether content carries the marker near the top.
func isGenerated(content []byte) bool {
	head := content
	if len(head) > 512 {
		head = head[:512]
	}
	return bytes.Contains(head, []byte(Marker))
}

// existingGenerated lists generated files below dir, as slash paths.
func existingGenerated(dir string) (map[string]bool, error) {
	out := map[string]bool{}
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) && path == dir {
				return fs.SkipAll
			}
			return err
		}
		if !d.Type().IsRegular() {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if isGenerated(data) {
			rel, _ := filepath.Rel(dir, path)
			out[filepath.ToSlash(rel)] = true
		}
		return nil
	})
	return out, err
}

// Check compares the files with the content of dir: generated files
// that are missing, differ, or are no longer produced (stale).
func Check(dir string, files Files) ([]Difference, error) {
	existing, err := existingGenerated(dir)
	if err != nil {
		return nil, err
	}
	var out []Difference
	for _, p := range files.Paths() {
		data, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(p)))
		switch {
		case errors.Is(err, fs.ErrNotExist):
			out = append(out, Difference{Path: p, Kind: DiffMissing})
		case err != nil:
			return nil, err
		case !bytes.Equal(data, files[p]):
			out = append(out, Difference{Path: p, Kind: DiffChanged})
		}
	}
	var stale []string
	for p := range existing {
		if _, ok := files[p]; !ok {
			stale = append(stale, p)
		}
	}
	sort.Strings(stale)
	for _, p := range stale {
		out = append(out, Difference{Path: p, Kind: DiffStale})
	}
	return out, nil
}

// Write writes the files below dir. It refuses, before writing
// anything, to replace a file that does not carry the generator marker
// unless force is set. Generated files below dir that are no longer
// produced are removed. It returns the paths it wrote.
func Write(dir string, files Files, force bool) ([]string, error) {
	var foreign []string
	for _, p := range files.Paths() {
		data, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(p)))
		if err == nil && !isGenerated(data) {
			foreign = append(foreign, p)
		} else if err != nil && !errors.Is(err, fs.ErrNotExist) {
			return nil, err
		}
	}
	if len(foreign) > 0 && !force {
		return nil, fmt.Errorf("%w: %s (use --force)", ErrWouldOverwrite, strings.Join(foreign, ", "))
	}
	existing, err := existingGenerated(dir)
	if err != nil {
		return nil, err
	}
	var written []string
	for _, p := range files.Paths() {
		full := filepath.Join(dir, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return written, err
		}
		if err := os.WriteFile(full, files[p], 0o644); err != nil {
			return written, err
		}
		written = append(written, p)
	}
	for p := range existing {
		if _, ok := files[p]; !ok {
			if err := os.Remove(filepath.Join(dir, filepath.FromSlash(p))); err != nil {
				return written, err
			}
		}
	}
	return written, nil
}
